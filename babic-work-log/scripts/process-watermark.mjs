import jpeg from 'jpeg-js'
import { PNG } from 'pngjs'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const SRC = '/root/.claude/uploads/a30ccd84-d19a-5349-b30c-c63098c53329/b7cf0578-IMG_2726.jpeg'
const outDir = join(__dirname, '..', 'public', 'brand')
mkdirSync(outDir, { recursive: true })

const raw = readFileSync(SRC)
const decoded = jpeg.decode(raw, { useTArray: true })
const { width, height, data } = decoded

// Threshold: background is warm cream (light), the mark is dark forest green.
// Use luminance to build a binary alpha mask, then find the tight bounding box.
const luminance = new Float32Array(width * height)
let minX = width,
  minY = height,
  maxX = 0,
  maxY = 0
const THRESHOLD = 150 // 0-255, pixels darker than this are "ink"

for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    const idx = (y * width + x) * 4
    const r = data[idx]
    const g = data[idx + 1]
    const b = data[idx + 2]
    const l = 0.2126 * r + 0.7152 * g + 0.0722 * b
    luminance[y * width + x] = l
    if (l < THRESHOLD) {
      if (x < minX) minX = x
      if (x > maxX) maxX = x
      if (y < minY) minY = y
      if (y > maxY) maxY = y
    }
  }
}

const pad = Math.round(Math.max(maxX - minX, maxY - minY) * 0.04)
minX = Math.max(0, minX - pad)
minY = Math.max(0, minY - pad)
maxX = Math.min(width - 1, maxX + pad)
maxY = Math.min(height - 1, maxY + pad)

const cropW = maxX - minX + 1
const cropH = maxY - minY + 1

function buildMask(outSize) {
  const png = new PNG({ width: outSize, height: outSize })
  const scale = Math.max(cropW, cropH) / outSize
  for (let oy = 0; oy < outSize; oy++) {
    for (let ox = 0; ox < outSize; ox++) {
      // sample-average a small box from source for smoother downscale edges
      const sx0 = minX + ox * scale
      const sy0 = minY + oy * scale
      const sx1 = sx0 + scale
      const sy1 = sy0 + scale
      let sum = 0
      let count = 0
      for (let sy = Math.floor(sy0); sy < Math.ceil(sy1); sy++) {
        if (sy < 0 || sy >= height) continue
        for (let sx = Math.floor(sx0); sx < Math.ceil(sx1); sx++) {
          if (sx < 0 || sx >= width) continue
          sum += luminance[sy * width + sx]
          count++
        }
      }
      const avg = count > 0 ? sum / count : 255
      // map luminance to alpha: dark ink -> opaque, cream bg -> transparent
      const alpha = Math.max(0, Math.min(255, Math.round(((THRESHOLD + 20 - avg) / (THRESHOLD + 20)) * 255)))
      const idx = (outSize * oy + ox) << 2
      png.data[idx] = 0x3a
      png.data[idx + 1] = 0x35
      png.data[idx + 2] = 0x2e
      png.data[idx + 3] = alpha
    }
  }
  return png
}

const full = buildMask(512)
writeFileSync(join(outDir, 'cipka-b.png'), PNG.sync.write(full))
console.log('wrote public/brand/cipka-b.png', { srcW: width, srcH: height, cropW, cropH })

const small = buildMask(160)
const base64 = PNG.sync.write(small).toString('base64')
writeFileSync(
  join(__dirname, '..', 'src', 'lib', 'watermarkAsset.ts'),
  `// Generated by scripts/process-watermark.mjs from the BabicADesigns Čipka-B mark.\nexport const CIPKA_B_BASE64 = 'data:image/png;base64,${base64}'\n`,
)
console.log('wrote src/lib/watermarkAsset.ts')
